    private static void AssertHex(string vector, PlmEncodedManifest encoded) =>
        Assert.Equal(GoldenHex[vector], Convert.ToHexString(encoded.CanonicalBytes).ToLowerInvariant());

    private static (ProductMaster Product, ProductMaterial Bom, ProductProcess Routing) BaseRows()
    {
        var product = new ProductMaster
        {
            Id = Guid.NewGuid(), ProductCd = "P-001", ItemCd = "ITEM-1", SetProductCd = "P-001",
            ParentChildDiv = "0", SetRatio = 1.0m, CpItemName1 = "Cafe\u0301", TrackingMode = 0
        };
        var bom = new ProductMaterial
        {
            Id = Guid.NewGuid(), ProductCd = "P-001", ProcessCd = "PROC-A", MaterialCd = "MAT-A",
            MaterialTypeDiv = "1", UsageType = 1, UnitUsage = 1m, SortOrder = 10
        };
        var routing = new ProductProcess
        {
            Id = Guid.NewGuid(), ProductCd = "P-001", TaskCd = "TASK-A", ProcessCd = "PROC-A",
            MachineFixedFlg = false, SortOrder = 10
        };
        return (product, bom, routing);
    }

    private static PlmEncodedManifest Encode(ProductMaster product, ProductMaterial bom, ProductProcess routing) =>
        PlmCanonicalWriter.Encode(Tenant, [PlmSnapshotProjector.Product(product), PlmSnapshotProjector.Bom(bom), PlmSnapshotProjector.Routing(routing)]);

    [Fact]
    public void GoldenVectorsExactBytes()
    {
        var (product, bom, routing) = BaseRows();
        var original = Encode(product, bom, routing);
        Assert.Equal(BaseDigest, original.ManifestDigest);
        AssertHex("V01", original);
        Assert.Equal("16cd1092c0a15f1f6f5dc68404ce95b68244a4c62243d645bbbeb35afe23b116", original.Items[0].ItemDigest);
        Assert.Equal("b5653df10ec98c1e83e6b718d459357a75528a9dcb00ae423797e732b008cbd6", original.Items[1].ItemDigest);
        Assert.Equal("6c8aef4377c406b0e25fef687a24ec94429fb3f0034971c41e08868d2207af44", original.Items[2].ItemDigest);
        var json = Encoding.UTF8.GetString(original.CanonicalBytes);
        Assert.Contains("\"cpItemName1\":\"Café\"", json);
        Assert.Contains("\"setRatio\":1,", json);
        Assert.DoesNotContain("\\u00e9", json);
        Assert.False(json.Contains("\uFEFF", StringComparison.Ordinal));
        Assert.Equal(original.CanonicalBytes, PlmCanonicalWriter.Encode(Tenant,
            [PlmSnapshotProjector.Routing(routing), PlmSnapshotProjector.Bom(bom), PlmSnapshotProjector.Product(product)]).CanonicalBytes); // V02
        product.SetRatio = 1.00m; bom.UnitUsage = 1.0000m;
        Assert.Equal(BaseDigest, Encode(product, bom, routing).ManifestDigest); // V03
        product.CpItemName1 = "Café";
        Assert.Equal(BaseDigest, Encode(product, bom, routing).ManifestDigest); // V04
        product.ProductShape = "BOX";
        var v05Product = Encode(product, bom, routing);
        Assert.Equal("314923554799720af0c238d49ca2c7c0a53175beb112e7d88d603ab9157dfea6", v05Product.ManifestDigest);
        AssertHex("V05-PRODUCT", v05Product);
        product.ProductShape = null; bom.UnitUsage = 2m;
        var v05Bom = Encode(product, bom, routing);
        Assert.Equal("574b82fa9d78d36258bb532cbf825607d4ed12dee6ec19affb394b74277e18f4", v05Bom.ManifestDigest);
        AssertHex("V05-BOM", v05Bom);
        bom.UnitUsage = 1m; routing.MachineFixedFlg = true;
        var v05Routing = Encode(product, bom, routing);
        Assert.Equal("057fc4140cef2c429175133018925a42452a7e699c2baa59563c8af026941260", v05Routing.ManifestDigest);
        AssertHex("V05-ROUTING", v05Routing);
        routing.MachineFixedFlg = false;
        var absent = PlmSnapshotProjector.Product(product);
        absent = absent with { Content = absent.Content.Where(x => x.Name != "productShape").ToArray() };
        Assert.Equal("PLM_CANONICAL_SCHEMA", Assert.Throws<PlmException>(() =>
            PlmCanonicalWriter.Encode(Tenant, [absent, PlmSnapshotProjector.Bom(bom), PlmSnapshotProjector.Routing(routing)])).Code); // V06
        Assert.Equal("PLM_DUPLICATE_ITEM", Assert.Throws<PlmException>(() =>
            PlmCanonicalWriter.Encode(Tenant, [PlmSnapshotProjector.Product(product), PlmSnapshotProjector.Bom(bom), PlmSnapshotProjector.Bom(bom), PlmSnapshotProjector.Routing(routing)])).Code); // V07
        product.Id = Guid.NewGuid(); product.RowVersion = [1, 2, 3, 4, 5, 6, 7, 8];
        bom.Id = Guid.NewGuid(); bom.RowVersion = [8, 7, 6, 5, 4, 3, 2, 1];
        Assert.Equal(BaseDigest, Encode(product, bom, routing).ManifestDigest); // V08
    }

    [Fact]
    public void ItemIdentityAndDigest()
    {
        var (product, bom, routing) = BaseRows();
        var encoded = Encode(product, bom, routing);
        Assert.Equal("{\"productCd\":\"P-001\"}", encoded.Items[0].IdentityKey);
        Assert.Equal("{\"productCd\":\"P-001\",\"processCd\":\"PROC-A\",\"materialCd\":\"MAT-A\"}", encoded.Items[1].IdentityKey);
        Assert.Equal("{\"productCd\":\"P-001\",\"taskCd\":\"TASK-A\"}", encoded.Items[2].IdentityKey);
        Assert.All(encoded.Items, x => Assert.Equal(64, x.ItemDigest.Length));
        Assert.Equal(45, encoded.Items[0].Projection.Content.Count);
        Assert.Equal(9, encoded.Items[1].Projection.Content.Count);
        Assert.Equal(37, encoded.Items[2].Projection.Content.Count);
    }

    [Fact]
    public void AllowedFieldsAndExclusions()
    {
        var (product, bom, routing) = BaseRows();
        var digest = Encode(product, bom, routing).ManifestDigest;
        product.CustomerCd = "OTHER"; product.Creator = "other"; product.RowVersion = [1];
        bom.SupplyPrice = 500m; routing.PurchasePrice = 600m;
        Assert.Equal(digest, Encode(product, bom, routing).ManifestDigest);
        product.ProductShape = "BOX";
        Assert.NotEqual(digest, Encode(product, bom, routing).ManifestDigest);
        product.ProductShape = null; bom.UnitUsage = 2m;
        Assert.NotEqual(digest, Encode(product, bom, routing).ManifestDigest);
        bom.UnitUsage = 1m; routing.ProcessCd = "PROC-B";
        Assert.NotEqual(digest, Encode(product, bom, routing).ManifestDigest);
    }
