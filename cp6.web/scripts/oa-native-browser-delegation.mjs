import { expect } from '@playwright/test'
import path from 'node:path'

export async function runNativeDelegation(page, browser, origin, output, runtime, steps, login, usePage) {
  await page.goto(origin + '/oa/flow-admin')
  await page.getByRole('tab', { name: '表单版本启停', exact: true }).click()
  const activation = page.getByRole('region', { name: '准确版本启停' })
  await activation.getByRole('button', { name: '读取表单', exact: true }).click()
  await activation.getByRole('button', { name: 'Browser accepted form · personal', exact: true }).click()
  await activation.getByLabel('启停原因').fill('Stop new admissions while the accepted task continues')
  await activation.getByRole('button', { name: '停用当前配置', exact: true }).click()
  await expect(activation.getByRole('status')).toContainText('确认')

  await page.goto(origin + '/oa/settings')
  const grants = page.getByRole('region', { name: '当前任务委派' })
  await grants.getByLabel('搜索同租户代理人').fill('browser-delegate')
  await grants.getByRole('button', { name: '搜索人员', exact: true }).click()
  await grants.getByRole('combobox', { name: /^代理人/ }).selectOption(process.env.CP6_OA_BROWSER_DELEGATE)
  // Use minute-aligned fixture bounds: Chromium canonicalizes trailing fractional zeroes during fill.
  await grants.getByLabel('开始时间（UTC，含）').fill(new Date(Date.now() - 60000).toISOString().slice(0, 16))
  await grants.getByLabel('结束时间（UTC，不含）').fill(new Date(Date.now() + 3600000).toISOString().slice(0, 16))
  await grants.getByLabel('同意', { exact: true }).check()
  await grants.getByLabel('流程标识，逗号分隔').fill('native-inbox')
  await grants.getByLabel('说明', { exact: true }).fill('Actual browser authorizes exact task scope')
  await grants.getByRole('button', { name: '创建授权', exact: true }).click()
  await expect(grants.getByRole('status')).toContainText('授权变更已确认')
  steps.push('FORM stops new admissions; principal creates current scoped task grant through UI')

  const delegate = await browser.newPage({ viewport: { width: 1440, height: 1050 }, locale: 'zh-CN' })
  usePage(delegate)
  await login(delegate, 'browser-delegate')
  await delegate.goto(origin + '/oa/inbox')
  await delegate.getByRole('button', { name: '读取可代理人员', exact: true }).click()
  await delegate.getByLabel('当前本人或代理身份').selectOption(process.env.CP6_OA_BROWSER_ACTOR)
  const rows = delegate.locator('[aria-label="当前任务列表"]')
  const row = rows.locator('tr').filter({ hasText: 'Browser submitted record' })
  await row.getByRole('button', { name: '查看详情', exact: true }).click()
  const detail = delegate.getByRole('article', { name: '当前授权详情' })
  await expect(detail).toContainText(runtime.flowInstanceId)
  await expect(detail).toContainText(runtime.formVersionId)
  await expect(detail).toContainText(runtime.flowVersionId)
  await detail.getByRole('button', { name: '标记已读', exact: true }).click()
  await expect(detail).toContainText('实际阅读人 ' + process.env.CP6_OA_BROWSER_DELEGATE)
  await detail.getByRole('button', { name: '读取当前办理条件', exact: true }).click()
  const task = delegate.locator('.task-panel')
  await expect(task.getByRole('heading', { name: 'Browser accepted form', exact: true })).toBeVisible()
  await task.getByPlaceholder('办理意见').fill('Browser delegate approves the exact accepted submission')
  const decision = delegate.waitForResponse(r => /\/api\/oa\/v2\/tasks\/[^/]+\/decisions$/.test(new URL(r.url()).pathname) && r.request().method() === 'POST')
  await task.getByRole('button', { name: '同意', exact: true }).click()
  expect((await decision).status()).toBe(200)
  await expect(detail).toContainText('实际办理人 ' + process.env.CP6_OA_BROWSER_DELEGATE)
  steps.push('independent delegate login, explicit principal choice, first-read fact and real task approval after FORM disabled')
  await delegate.screenshot({ path: path.join(output, 'delegated-task-approved.png'), fullPage: true })
}
